import { writeFileSync } from "node:fs";
import { DatabaseSync } from "node:sqlite";
import { getMigrations } from "better-auth/db/migration";
import { authOptions } from "../src/modules/auth/internal/options.ts";

/** Writes Better Auth's tables, for the options the app really uses, as the first control-plane migration. */
const settings = {
  baseUrl: "https://schema.invalid",
  secret: "schema-only-secret-schema-only-secret",
  sendFrom: "x@schema.invalid",
  google: { clientId: "x", clientSecret: "x" },
  github: { clientId: "x", clientSecret: "x" },
};
const mailer = { send: async () => ({ _tag: "Sent", messageId: "" }) as const };
const { compileMigrations } = await getMigrations(authOptions(settings, mailer, new DatabaseSync(":memory:")));
const sql = await compileMigrations();
writeFileSync(
  "migrations/control/0001_auth.sql",
  `-- Better Auth's tables. Generated by scripts/auth-schema.ts; do not edit.\n${sql.trim()}\n`,
);
console.log("Wrote migrations/control/0001_auth.sql");
