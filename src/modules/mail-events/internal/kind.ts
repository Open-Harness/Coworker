import type { MailIs } from "../types.ts";
import { header, type Parsed } from "./parse.ts";

const AWAY_SUBJECT = /^\s*(?:(?:re|aw):\s*)?(?:automatic reply|auto[- ]?reply|auto[- ]?respon|out of (?:the )?office)/iu;
const NOBODY = /^(?:no-?reply|do-?not-?reply|donotreply|mailer-daemon|postmaster|bounces?)(?:[+._-][^@]*)?@/iu;

const lower = (value: string | undefined): string => (value ?? "").trim().toLowerCase();

/** Someone is away: it says so itself, or by its subject when a server says nothing else. */
function away(parsed: Parsed, subject: string): boolean {
  if (lower(header(parsed, "auto-submitted")).startsWith("auto-replied")) return true;
  if (["x-autoreply", "x-autorespond"].some((key) => header(parsed, key) !== undefined)) return true;
  return AWAY_SUBJECT.test(subject);
}

function invite(parsed: Parsed): boolean {
  return (
    parsed.parts.some(({ type, text }) => type === "text/calendar" && /^METHOD:(?:REQUEST|PUBLISH)\s*$/imu.test(text)) ||
    /text\/calendar[^;\n]*;[^\n]*method=request/iu.test(parsed.raw)
  );
}

/** What nobody typed: it says so, or it is from a name no person has. */
function machine(parsed: Parsed, from: string): boolean {
  const auto = lower(header(parsed, "auto-submitted"));
  if (auto !== "" && auto !== "no") return true;
  if (/^(?:bulk|junk|list|auto_reply)\b/u.test(lower(header(parsed, "precedence")))) return true;
  if (["list-unsubscribe", "x-auto-response-suppress", "x-autogenerated"].some((key) => header(parsed, key) !== undefined)) return true;
  return NOBODY.test(from);
}

/** What kind of mail it is, when it is not a report (see `isReport`). Only `person` and `invite` ask for anything. */
export function kindOf(parsed: Parsed, from: string, subject: string): Exclude<MailIs, "report"> {
  if (away(parsed, subject)) return "away";
  if (invite(parsed)) return "invite";
  if (header(parsed, "list-id") !== undefined) return "list";
  return machine(parsed, from) ? "machine" : "person";
}
